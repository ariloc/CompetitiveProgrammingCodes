int mecanico(int X, vector<int> &t) {
    int mini = sz(t);
    int r = 0, acc = 0;
    forn(i,sz(t)) {
        while (r < sz(t) && acc < X) {
            acc += t[r];
            ++r;
        }
        if (acc >= X) mini = min(mini,r-i);
        acc -= t[i];
    }
    return mini;
}
